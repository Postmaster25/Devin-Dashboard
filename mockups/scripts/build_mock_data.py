"""Build mockups/assets/mock-data.js from software_itam_eos_snapshots.zip.

The mockups embed a compact, dictionary-encoded extract so they open straight
from the file system (no server, no fetch). Dates are stored as day numbers
since 1970-01-01.

Usage (from the repo root):
    python mockups/scripts/build_mock_data.py
"""

import csv
import io
import json
import zipfile
from collections import defaultdict
from datetime import date
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "software_itam_eos_snapshots.zip"
TARGET = REPO / "mockups" / "assets" / "mock-data.js"
EPOCH = date(1970, 1, 1)


def day(value):
    return (date.fromisoformat(value) - EPOCH).days if value else None


def effective_eos(row):
    return day(row["extended_support_end_date"] or row["obsolete_date"] or row["end_of_life_date"])


class Index:
    def __init__(self):
        self.items, self.lookup = [], {}

    def __call__(self, key, item=None):
        if key not in self.lookup:
            self.lookup[key] = len(self.items)
            self.items.append(item if item is not None else key)
        return self.lookup[key]


def main():
    with zipfile.ZipFile(SOURCE) as zf:
        name = next(n for n in zf.namelist() if n.endswith(".csv"))
        rows = list(csv.DictReader(io.TextIOWrapper(zf.open(name), encoding="utf-8")))

    snapshots = sorted({r["snapshot_date"] for r in rows})
    latest = snapshots[-1]
    snap_idx = {s: i for i, s in enumerate(snapshots)}

    orgs, groups, envs, crits, cats, ci_types, products, hosts, editions = (Index() for _ in range(9))
    for r in sorted(rows, key=lambda r: (r["cio_org_name"], r["managed_by_group"], r["host_name"])):
        org = orgs(r["cio_org_name"], [r["cio_org_name"], r["cio_org_manager_name"]])
        grp = groups(r["managed_by_group"], [r["managed_by_group"], org, r["managed_by_group_manager_name"]])
        hosts(r["host_name"], [r["host_name"], grp, envs(r["environment"]), crits(r["business_criticality"]),
                               ci_types(r["ci_type"]), r["city"], r["country"], r["ci_id"]])

    cube = defaultdict(lambda: [0, 0])
    installs = []
    for r in rows:
        host = hosts.items[hosts.lookup[r["host_name"]]]
        snap_day = day(r["snapshot_date"])
        eff = effective_eos(r)
        cell = cube[(snap_idx[r["snapshot_date"]], host[1], host[2], host[3])]
        cell[0] += 1
        cell[1] += int(eff is not None and eff <= snap_day)
        if r["snapshot_date"] != latest:
            continue
        prod = products(r["normalized_product_name"], [r["normalized_product_name"], r["normalized_manufacturer"],
                                                        cats(r["product_category"])])
        installs.append([
            int(r["install_id"].removeprefix("SI")), hosts.lookup[r["host_name"]], prod, r["normalized_version"],
            editions(r["edition"]), day(r["end_of_life_date"]), day(r["extended_support_end_date"]),
            day(r["obsolete_date"]), day(r["aging_start_date"]),
        ])

    data = {
        "snapshots": [day(s) for s in snapshots],
        "orgs": orgs.items,
        "groups": groups.items,
        "envs": envs.items,
        "crits": crits.items,
        "cats": cats.items,
        "ciTypes": ci_types.items,
        "products": products.items,
        "editions": editions.items,
        "hosts": hosts.items,
        "installFields": ["installId", "host", "product", "version", "edition", "eol", "ext", "obs", "aging"],
        "installs": installs,
        "cubeFields": ["snapshot", "group", "env", "crit", "installs", "pastEos"],
        "cube": [[*k, *v] for k, v in sorted(cube.items())],
    }
    TARGET.write_text(
        "// Generated by mockups/scripts/build_mock_data.py from software_itam_eos_snapshots.zip.\n"
        "window.MOCK_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {TARGET.relative_to(REPO)}: {len(installs)} installs at {latest}, {len(data['cube'])} cube rows")


if __name__ == "__main__":
    main()
